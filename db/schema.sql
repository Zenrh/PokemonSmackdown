-- Oracle Database 12c or later. Run as your dedicated application user.
-- Creates new PS_ tables only. This script does not drop existing data.
CREATE TABLE ps_team (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(80 CHAR) NOT NULL,
    name_key VARCHAR2(80 CHAR) NOT NULL,
    row_version NUMBER(10) DEFAULT 0 NOT NULL,
    CONSTRAINT ps_team_name_uq UNIQUE (name_key),
    CONSTRAINT ps_team_name_ck CHECK (LENGTH(TRIM(name)) > 0),
    CONSTRAINT ps_team_version_ck CHECK (row_version >= 0)
);

CREATE TABLE ps_team_member (
    team_id NUMBER(19) NOT NULL,
    slot_no NUMBER(1) NOT NULL,
    pokemon_id NUMBER(3) NOT NULL,
    CONSTRAINT ps_team_member_pk PRIMARY KEY (team_id, slot_no),
    CONSTRAINT ps_team_member_uq UNIQUE (team_id, pokemon_id),
    CONSTRAINT ps_team_member_fk FOREIGN KEY (team_id) REFERENCES ps_team(id) ON DELETE CASCADE,
    CONSTRAINT ps_team_slot_ck CHECK (slot_no BETWEEN 1 AND 6),
    CONSTRAINT ps_team_pokemon_ck CHECK (pokemon_id BETWEEN 1 AND 151)
);

CREATE TABLE ps_battle (
    battle_key VARCHAR2(36 CHAR) PRIMARY KEY,
    team_label VARCHAR2(80 CHAR) NOT NULL,
    outcome VARCHAR2(8 CHAR) NOT NULL,
    player_turns NUMBER(10) NOT NULL,
    started_at TIMESTAMP NOT NULL,
    ended_at TIMESTAMP NOT NULL,
    CONSTRAINT ps_battle_outcome_ck CHECK (outcome IN ('WIN', 'LOSS', 'FLED')),
    CONSTRAINT ps_battle_turns_ck CHECK (player_turns >= 0),
    CONSTRAINT ps_battle_time_ck CHECK (ended_at >= started_at)
);

CREATE TABLE ps_battle_member (
    battle_key VARCHAR2(36 CHAR) NOT NULL,
    side_code CHAR(1) NOT NULL,
    slot_no NUMBER(1) NOT NULL,
    pokemon_id NUMBER(3) NOT NULL,
    CONSTRAINT ps_battle_member_pk PRIMARY KEY (battle_key, side_code, slot_no),
    CONSTRAINT ps_battle_member_uq UNIQUE (battle_key, side_code, pokemon_id),
    CONSTRAINT ps_battle_member_fk FOREIGN KEY (battle_key) REFERENCES ps_battle(battle_key) ON DELETE CASCADE,
    CONSTRAINT ps_battle_side_ck CHECK (side_code IN ('P', 'E')),
    CONSTRAINT ps_battle_slot_ck CHECK (slot_no BETWEEN 1 AND 6),
    CONSTRAINT ps_battle_pokemon_ck CHECK (pokemon_id BETWEEN 1 AND 151)
);

CREATE INDEX ps_battle_ended_ix ON ps_battle (ended_at);
